// ---------- 工具函数（页面用） ----------
/**
 * 给定届与期 id，列出该期所有作品。
 */
export function worksOf(gradeId, issueId) {
  return works[`${gradeId}-${issueId}`] || [];
}

/**
 * 给定届 id，列出该届所有期 + 作品数。
 */
export function issuesOf(gradeId) {
  return (issues[gradeId] || []).map((it) => ({
    ...it,
    worksCount: (works[`${gradeId}-${it.id}`] || []).length,
  }));
}

/**
 * 全站汇总（首页底部统计用）
 */
export function siteStats() {
  let issueTotal = 0;
  let worksTotal = 0;
  for (const g of grades) {
    issueTotal += (issues[g.id] || []).length;
    for (const it of issues[g.id] || []) {
      worksTotal += (works[`${g.id}-${it.id}`] || []).length;
    }
  }
  return {
    gradeCount: grades.length,
    issueTotal,
    worksTotal,
  };
}

